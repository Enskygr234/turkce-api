export function findIl(query) {
  const q = String(query ?? '').trim();
  if (/^\d{1,2}$/.test(q)) return ILLER[Number(q) - 1] ?? null;
  const norm = q.toLocaleLowerCase('tr');
  return ILLER.find((il) => il.ad.toLocaleLowerCase('tr') === norm) ?? null;
}
